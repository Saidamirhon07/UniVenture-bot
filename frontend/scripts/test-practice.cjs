const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname,'../src/lib/practiceSelection.ts'),'utf8');
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod = {exports:{}};
new Function('exports','module',compiled)(mod.exports,mod);
const {choosePractice} = mod.exports;
const bank = Array.from({length:8},(_,i)=>({id:`q${i}`}));
const records = {q0:{last_correct:true,review_due:'2026-09-10'},q1:{last_correct:false,review_due:'2026-09-09'},q2:{last_correct:true,review_due:'2026-09-07'}};
const original = JSON.stringify(bank);
assert.equal(choosePractice(bank,{},'learn','2026-09-08',0).length,5);
assert.equal(choosePractice(bank,{},'learn','2026-09-08',5)[0].id,'q5');
assert.equal(choosePractice(bank,records,'learn','2026-09-08',0)[0].id,'q3');
assert.deepEqual(choosePractice(bank,records,'review','2026-09-08',0).map(q=>q.id),['q1','q2']);
assert.deepEqual(choosePractice(bank,{},'review','2026-09-08',0),[]);
assert.deepEqual(choosePractice([],{},'timed','2026-09-08',0),[]);
assert.equal(JSON.stringify(bank),original);
assert.equal(new Set(choosePractice(bank,records,'learn','2026-09-08',11).map(q=>q.id)).size,5);
